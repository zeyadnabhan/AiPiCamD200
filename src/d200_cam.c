static void sensor_read(struct bflb_device_s *i2c, uint8_t reg, uint8_t *val)
{
    struct bflb_i2c_msg_s msgs[2];
    msgs[0].addr = GC2145_ADDR; msgs[0].flags = I2C_M_NOSTOP; msgs[0].buffer = &reg; msgs[0].length = 1;
    msgs[1].addr = GC2145_ADDR; msgs[1].flags = I2C_M_READ;   msgs[1].buffer = val;  msgs[1].length = 1;
    bflb_i2c_transfer(i2c, msgs, 2);
}

static void sensor_write(struct bflb_device_s *i2c, uint8_t reg, uint8_t val)
{
    struct bflb_i2c_msg_s msgs[2];
    msgs[0].addr = GC2145_ADDR; msgs[0].flags = I2C_M_NOSTOP; msgs[0].buffer = &reg; msgs[0].length = 1;
    msgs[1].addr = GC2145_ADDR; msgs[1].flags = 0;            msgs[1].buffer = &val; msgs[1].length = 1;
    bflb_i2c_transfer(i2c, msgs, 2);
}

uint8_t d200_id0 = 0xEE, d200_id1 = 0xEE;

static int sensor_init(struct bflb_device_s *i2c)
{
    uint32_t i;
    bflb_i2c_init(i2c, 100000);
    sensor_read(i2c, 0xf0, &d200_id0);
    sensor_read(i2c, 0xf1, &d200_id1);
    if (d200_id0 != 0x21 || d200_id1 != 0x45) return 0;
    for (i = 0; i < sizeof(gc2145_init_list) / sizeof(gc2145_init_list[0]); i++) {
        sensor_write(i2c, (uint8_t)gc2145_init_list[i].address, gc2145_init_list[i].value);
    }
    return 1;
}

